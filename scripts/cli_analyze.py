"""Headless CLI to analyze the delay between audio tracks, no GUI required.

Two capture modes:
  1. --wav-dir: analyze already-recorded WAV files (e.g. generated by
     gen_test_signals.py), to validate the algorithm without hardware.
  2. --live: capture in real time from PC audio devices (by name, see
     `python scripts/cli_analyze.py --list-devices`).

OBS integration (both modes):
  --dry-run   connect to OBS, compute the target offsets, print what would
              change (current vs. new offset) without writing anything.
  --apply     same as --dry-run, but actually writes the new offsets via
              obs-websocket.

Map track IDs to OBS input names with --obs-input TRACK_ID=INPUT_NAME; a
track without an explicit mapping falls back to using its own track_id as
the OBS input name.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

import numpy as np
from scipy.io import wavfile

from obs_audio_sync.audio.capture import MultiDeviceRecorder
from obs_audio_sync.audio.devices import list_input_devices
from obs_audio_sync.core.models import CapturedAudio, DelayResult, TrackConfig
from obs_audio_sync.dsp.offsets import clamp_offset_ms, resolve_target_offsets
from obs_audio_sync.dsp.onset_align import onset_align_delay
from obs_audio_sync.dsp.preprocessing import prepare_for_correlation
from obs_audio_sync.obs.client import ObsClient
from obs_audio_sync.obs.sync_ops import get_sync_offset_ms, set_sync_offset_ms

TARGET_FS = 48000


def load_wav_tracks(wav_dir: Path) -> dict[str, CapturedAudio]:
    tracks: dict[str, CapturedAudio] = {}
    for wav_path in sorted(wav_dir.glob("*.wav")):
        fs, data = wavfile.read(wav_path)
        if data.dtype.kind == "i":
            data = data.astype(np.float32) / np.iinfo(data.dtype).max
        tracks[wav_path.stem] = CapturedAudio(track_id=wav_path.stem, samples=data, fs=fs)
    return tracks


def analyze(
    captured: dict[str, CapturedAudio],
    reference_id: str,
    max_tau: float,
    confidence_threshold: float,
) -> tuple[list[DelayResult], dict[str, float], list[str]]:
    if reference_id not in captured:
        raise SystemExit(f"Reference track '{reference_id}' not found among: {list(captured)}")

    prepared = {
        track_id: prepare_for_correlation(audio.samples, audio.fs, TARGET_FS)
        for track_id, audio in captured.items()
    }
    ref_signal = prepared[reference_id]

    delays = [DelayResult(track_id=reference_id, delay_sec=0.0, confidence=1.0)]
    for track_id, signal in prepared.items():
        if track_id == reference_id:
            continue
        delay_sec, confidence = onset_align_delay(signal, ref_signal, TARGET_FS, max_tau=max_tau)
        delays.append(DelayResult(track_id=track_id, delay_sec=delay_sec, confidence=confidence))

    target_offsets_ms, rejected = resolve_target_offsets(delays, confidence_threshold)
    return delays, target_offsets_ms, rejected


def print_report(delays: list[DelayResult], target_offsets_ms: dict[str, float], rejected: list[str]) -> None:
    print(f"{'Track':<30} {'Delay (ms)':>12} {'Confidence':>12} {'OBS offset (ms)':>16}")
    for d in sorted(delays, key=lambda x: x.track_id):
        offset = target_offsets_ms.get(d.track_id)
        offset_str = f"{offset:>16.1f}" if offset is not None else f"{'REJECTED':>16}"
        print(f"{d.track_id:<30} {d.delay_sec * 1000:>12.2f} {d.confidence:>12.2f} {offset_str}")
    if rejected:
        print(f"\nTracks rejected (confidence below threshold): {rejected}")


def parse_obs_input_map(items: list[str] | None) -> dict[str, str]:
    mapping: dict[str, str] = {}
    for item in items or []:
        track_id, _, obs_input_name = item.partition("=")
        mapping[track_id] = obs_input_name
    return mapping


def sync_with_obs(
    target_offsets_ms: dict[str, float],
    obs_input_map: dict[str, str],
    host: str,
    port: int,
    password: str,
    apply: bool,
) -> None:
    verb = "Applying" if apply else "Dry run: would apply"
    print(f"\n{verb} offsets against OBS at {host}:{port}...")

    with ObsClient(host=host, port=port, password=password) as client:
        for track_id, new_offset_ms in target_offsets_ms.items():
            input_name = obs_input_map.get(track_id, track_id)
            clamped_offset_ms, was_clamped = clamp_offset_ms(new_offset_ms)
            current_offset_ms = get_sync_offset_ms(client, input_name)

            clamp_note = "  (clamped to OBS limits)" if was_clamped else ""
            print(
                f"  {input_name}: {current_offset_ms:.1f} ms -> {clamped_offset_ms:.1f} ms{clamp_note}"
            )

            if apply:
                set_sync_offset_ms(client, input_name, clamped_offset_ms)

    print("Done." if apply else "Dry run complete: nothing was written.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--list-devices", action="store_true", help="List available WASAPI input devices")
    parser.add_argument("--wav-dir", type=Path, help="Analyze WAVs in this folder instead of capturing live")
    parser.add_argument(
        "--live",
        nargs="+",
        metavar="TRACK_ID=DEVICE_NAME",
        help="Capture live, e.g.: --live pa='Line In (USB Audio)' ambient='RODE Wireless'",
    )
    parser.add_argument("--duration", type=float, default=8.0, help="Live capture duration in seconds")
    parser.add_argument("--reference", type=str, help="track_id to use as the reference")
    parser.add_argument("--max-tau", type=float, default=2.0)
    parser.add_argument("--confidence-threshold", type=float, default=0.2)

    obs_group = parser.add_argument_group("OBS integration")
    obs_group.add_argument("--dry-run", action="store_true", help="Connect to OBS and show what would change")
    obs_group.add_argument("--apply", action="store_true", help="Connect to OBS and actually write the new offsets")
    obs_group.add_argument("--obs-host", default="localhost")
    obs_group.add_argument("--obs-port", type=int, default=4455)
    obs_group.add_argument("--obs-password", default="")
    obs_group.add_argument(
        "--obs-input",
        nargs="+",
        metavar="TRACK_ID=OBS_INPUT_NAME",
        help="Map a track_id to its OBS input name (defaults to the track_id itself if omitted)",
    )
    args = parser.parse_args()

    if args.list_devices:
        for dev in list_input_devices():
            print(f"{dev.name!r}  (input channels: {dev.max_input_channels}, fs: {dev.default_samplerate:.0f})")
        return

    if args.wav_dir:
        captured = load_wav_tracks(args.wav_dir)
    elif args.live:
        tracks = []
        for item in args.live:
            track_id, _, device_name = item.partition("=")
            tracks.append(
                TrackConfig(
                    id=track_id, display_name=track_id, obs_input_name="", capture_device_name=device_name
                )
            )
        recorder = MultiDeviceRecorder(tracks)
        print(f"Capturing {args.duration}s from {len(tracks)} device(s)...")
        captured = recorder.capture_window(args.duration)
    else:
        parser.error("Specify --wav-dir, --live or --list-devices")
        return

    reference_id = args.reference or next(iter(captured))
    delays, target_offsets_ms, rejected = analyze(
        captured, reference_id, args.max_tau, args.confidence_threshold
    )
    print_report(delays, target_offsets_ms, rejected)

    if args.dry_run or args.apply:
        obs_input_map = parse_obs_input_map(args.obs_input)
        sync_with_obs(
            target_offsets_ms,
            obs_input_map,
            args.obs_host,
            args.obs_port,
            args.obs_password,
            apply=args.apply,
        )


if __name__ == "__main__":
    main()
